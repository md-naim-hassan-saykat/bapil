#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Sequential numbering of references.

The sources cite references by stable keys: numbers 1 to 83 are the entries of the White
Paper bibliography and 84 onwards are the entries of refs_new.md. The published documents
number their references 1, 2, 3 ... in the order in which they are first cited. This module
computes that order and rewrites the citations.

* The Technical Blueprint uses one numbering for both editions, taken from the English text
  (tables included, in the position where they appear), so that the English and Bangla
  editions cite the same numbers.
* The Summary numbers its own (short) reference list.

Citations have the form [84] or [84, 106]; code blocks and inline code are left untouched.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CITE_RE = re.compile(r"(?<![!\w\]])\[(\d[\d,\s]*)\](?![(\[])")
CODE_RE = re.compile(r"(```.*?```|`[^`\n]*`)", re.S)
WP_LAST = 83   # keys 1..83 come from the White Paper bibliography


def _prose_parts(text):
    parts = CODE_RE.split(text)
    return parts  # even indices are prose


def first_citation_order(text):
    """Reference keys in order of first citation (prose only)."""
    seen, order = set(), []
    for i, part in enumerate(_prose_parts(text)):
        if i % 2:
            continue
        for m in CITE_RE.finditer(part):
            for k in m.group(1).split(","):
                k = k.strip()
                if k.isdigit() and int(k) not in seen:
                    seen.add(int(k))
                    order.append(int(k))
    return order


def make_map(order, valid=None):
    keys = [k for k in order if valid is None or k in valid]
    return {k: i + 1 for i, k in enumerate(keys)}


def apply_map(text, mapping):
    """Rewrite every citation group with the new numbers (sorted, comma separated)."""
    def group(m):
        keys = [k.strip() for k in m.group(1).split(",") if k.strip()]
        if not all(k.isdigit() and int(k) in mapping for k in keys):
            return m.group(0)        # not a reference citation (or unknown key): leave as is
        nums = sorted({mapping[int(k)] for k in keys})
        return "[%s]" % ", ".join(str(n) for n in nums)
    parts = _prose_parts(text)
    for i in range(0, len(parts), 2):
        parts[i] = CITE_RE.sub(group, parts[i])
    return "".join(parts)


def _expand_includes(text, depth=0):
    if depth > 3:
        raise SystemExit("INCLUDE nested too deeply")
    def inc(m):
        with open(os.path.join(HERE, m.group(1)), encoding="utf-8") as fh:
            return _expand_includes(fh.read().strip("\n"), depth + 1)
    return re.sub(r"<!-- INCLUDE:([\w./-]+) -->", inc, text)


def blueprint_text_en(table_md):
    """English Blueprint body (up to the reference list) with tables in place.
    table_md: function(table_id) -> Markdown of that table with the original keys."""
    with open(os.path.join(HERE, "BAPIL_Technical_Blueprint_en.src.md"), encoding="utf-8") as fh:
        text = _expand_includes(fh.read())
    text = text.split("{{REFERENCES}}")[0]
    return re.sub(r"<!-- TABLE:(\d\d) -->", lambda m: table_md(m.group(1)), text)


_BP_MAP = None


def blueprint_map():
    """{key: number} for the Technical Blueprint (both editions)."""
    global _BP_MAP
    if _BP_MAP is None:
        import make_tables as mt          # imported here: make_tables also imports this module
        meta = mt.load_meta()
        by_id = {t["id"]: t for t in mt.TABLES}
        text = blueprint_text_en(lambda tid: mt.md_table(by_id[tid], "en", meta))
        _BP_MAP = make_map(first_citation_order(text))
    return _BP_MAP


def map_table(t, mapping):
    """Copy of a table definition with its citations renumbered (both languages)."""
    import copy
    t = copy.deepcopy(t)
    for lang in ("en", "bn"):
        t["title"][lang] = apply_map(t["title"][lang], mapping)
        t["rows"][lang] = [[apply_map(c, mapping) for c in row] for row in t["rows"][lang]]
        if t.get("note", {}).get(lang):
            t["note"][lang] = apply_map(t["note"][lang], mapping)
    return t


def write_key_table(path):
    """Markdown table: source key -> Blueprint reference number (for records that cite keys)."""
    import assemble
    refs = assemble.all_references()
    rows = []
    for key, num in sorted(blueprint_map().items(), key=lambda kv: kv[1]):
        first = refs[key].split("\n")[0]
        first = re.sub(r"^\[\d+\]\s*", "", first)
        src = "White Paper [%d]" % key if key <= WP_LAST else "refs_new.md [%d]" % key
        rows.append("| %d | %d | %s | %s |" % (num, key, src, first.replace("|", "/")))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# Reference numbers in the Technical Blueprint\n\n"
                 "Generated by `blueprint/src/refnum.py` during the build. The published Blueprint numbers its references "
                 "in order of first citation (both editions use the same numbers). The sources cite stable keys: 1 to 83 are "
                 "the White Paper bibliography and 84 onwards are the entries of `blueprint/src/refs_new.md`. Internal review "
                 "records written before 22 October 2026 cite keys.\n\n"
                 "| Blueprint number | Source key | Origin | First line of the entry |\n|---:|---:|---|---|\n")
        fh.write("\n".join(rows) + "\n")


if __name__ == "__main__":
    import sys
    if len(sys.argv) == 3 and sys.argv[1] == "--key-table":
        write_key_table(sys.argv[2])
    else:
        sys.exit("usage: refnum.py --key-table OUT.md")
