#!/usr/bin/env python3
"""Write blueprint/MANIFEST.md: every deliverable of the Technical Blueprint package with size and SHA-256.

Run from anywhere after a build:  python3 blueprint/make_manifest.py
"""
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

GROUPS = [
    ("Publication PDFs", ["releases/v1.1"], (".pdf",)),
    ("Assembled Markdown editions", ["blueprint"], (".md",), ("BAPIL_",)),
    ("Editable masters and build sources", ["blueprint/src", "blueprint/src/en", "blueprint/src/bn"],
     (".md", ".py", ".tex", ".lua", ".json")),
    ("Budget data (CSV)", ["blueprint/data"], (".csv",)),
    ("Build script and documentation", ["blueprint"], (".sh", ".py", ".md"), ("build_", "make_", "README", "CHANGES", "QA_", "SOURCES")),
    ("Zenodo metadata draft and checklist", ["blueprint/zenodo"], (".json", ".html", ".md", ".sh")),
    ("Figures (TikZ, PDF, PNG; EN and BN)", ["blueprint/figures"], (".tex", ".pdf", ".png")),
    ("Tables (LaTeX, PDF, PNG; EN and BN)", ["blueprint/tables"], (".tex", ".pdf", ".png")),
    ("Tables (Markdown; EN and BN)", ["blueprint/tables/md"], (".md",)),
]


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    out = ["# Manifest: BAPIL Technical Blueprint, Version 1.0", "",
           "Generated by `blueprint/make_manifest.py` after the build. Paths are relative to the repository root. "
           "Internal review records (`blueprint/review/`) are listed separately and are not part of the publication.", ""]
    total = 0
    for group in GROUPS + [("Internal review records (not part of the publication)", ["blueprint/review"], (".md", ".pdf", ".sh", ".tex"))]:
        title, dirs, exts = group[0], group[1], group[2]
        prefixes = group[3] if len(group) > 3 else None
        rows = []
        for d in dirs:
            full = os.path.join(ROOT, d)
            if not os.path.isdir(full):
                continue
            for name in sorted(os.listdir(full)):
                p = os.path.join(full, name)
                if not os.path.isfile(p) or not name.endswith(exts) or name == "MANIFEST.md":
                    continue
                if prefixes and not name.startswith(prefixes):
                    continue
                rows.append((os.path.relpath(p, ROOT), os.path.getsize(p), sha(p)))
        out += ["## %s (%d files)" % (title, len(rows)), "", "| File | Bytes | SHA-256 |", "|---|---:|---|"]
        out += ["| `%s` | %d | `%s` |" % r for r in rows] + [""]
        total += len(rows)
    out.insert(4, "Files listed: %d." % total)
    out.insert(5, "")
    with open(os.path.join(HERE, "MANIFEST.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("wrote blueprint/MANIFEST.md (%d files)" % total)


if __name__ == "__main__":
    main()
